pub enum AudioMsg {
    /// One Opus packet plus its 16-bit sequence number (wraps).
    Packet { seq: u16, data: Vec<u8> },
    /// A new connection started: reset decoder, sequence tracking, denoiser.
    Reset,
    Stop,
}

pub type AudioSender = SyncSender<AudioMsg>;

