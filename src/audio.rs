pub const SINK_NAME: &str = "PhoneMicSink";
pub const SOURCE_NAME: &str = "PhoneVirtualMic";
const SINK_DESC: &str = "Phone_Mic_Sink";
const CONF_FILENAME: &str = "99-phone-mic.conf";
const NAME_MARKER_PREFIX: &str = "# phone-mic-name:";

const SAMPLE_RATE: u32 = 48_000;
/// 10 ms @ 48 kHz mono (what Opus and RNNoise operate on).
const FRAME: usize = 480;
/// We output 2 channels (stereo L+R) into the sink so PipeWire/WirePlumber and
/// all WebRTC/Discord/OBS clients link both FL and FR ports reliably.
const OUT_CHANNELS: usize = 2;
const MAX_FRAME_BYTES: usize = FRAME * OUT_CHANNELS * 4; // stereo f32le
/// Largest Opus frame (120 ms) at 48 kHz.
const MAX_DECODE_SAMPLES: usize = 5760;
/// Queue between network threads and the audio thread.
const CHANNEL_CAP: usize = 128;
/// If more than this many packets are waiting, the oldest are decoded (to keep
/// decoder state valid) but not played, so latency never grows unbounded.
const MAX_BACKLOG_PACKETS: usize = 4;

