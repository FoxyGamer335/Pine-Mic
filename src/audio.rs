fn s16_mode() -> bool {
    static MODE: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    // s16le by default; PHONEMIC_F32=1 switches to float32le
    *MODE.get_or_init(|| std::env::var_os("PHONEMIC_F32").is_none())
}

fn pactl(args: &[&str]) -> Result<String> {
    let out = Command::new("pactl")
    .args(args)
    .env("LC_ALL", "C")
    .output()
    .context("failed to run `pactl` (install libpulse / pulseaudio-utils and run pipewire-pulse)")?;
    if !out.status.success() {
        bail!(
            "`pactl {}` failed: {}",
            args.join(" "),
              String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// `pactl load-module ...` prints the new module index on stdout.
fn load_module(args: &[&str]) -> Result<u32> {
    let mut full = vec!["load-module"];
    full.extend_from_slice(args);
    let out = pactl(&full)?;
    out.trim()
    .parse::<u32>()
    .with_context(|| format!("unexpected output from pactl load-module: {:?}", out.trim()))
}

fn unload_module(id: u32) {
    if let Err(e) = pactl(&["unload-module", &id.to_string()]) {
        eprintln!("warning: could not unload module {id}: {e:#}");
    }
}

/// Sanitize user-supplied microphone description so quotes/control chars cannot
/// break `pactl` module argument parsing or PipeWire config syntax.
fn sanitize_description(raw: &str) -> String {
    let cleaned: String = raw
    .chars()
    .filter(|c| !c.is_control() && *c != '"' && *c != '\'' && *c != '\\')
    .collect();
    let trimmed = cleaned.trim();
    if trimmed.is_empty() {
        DEFAULT_MIC_NAME.to_string()
    } else {
        trimmed.to_string()
    }
}

fn pipewire_conf_path() -> Option<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
    .map(PathBuf::from)
    .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))?;
    Some(base.join("pipewire").join("pipewire-pulse.conf.d").join(CONF_FILENAME))
}

fn write_pipewire_conf(desc: &str) -> Result<()> {
    let Some(path) = pipewire_conf_path() else {
        return Ok(());
    };
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
        .with_context(|| format!("cannot create directory {}", parent.display()))?;
    }
    let content = format!(
        "{NAME_MARKER_PREFIX} {desc}\n\
# Automatically generated by phone-mic. Keeps the virtual microphone across reboots.\n\
pulse.cmd = [\n\
\x20   {{ cmd = \"load-module\" args = \"module-null-sink sink_name={SINK_NAME} sink_properties=\\\"device.description='{SINK_DESC}'\\\" rate={SAMPLE_RATE} channels=2 channel_map=front-left,front-right\" flags = [ \"nofail\" ] }}\n\
\x20   {{ cmd = \"load-module\" args = \"module-remap-source master={SINK_NAME}.monitor source_name={SOURCE_NAME} source_properties=\\\"device.description='{desc}'\\\" rate={SAMPLE_RATE} channels=2 master_channel_map=front-left,front-right channel_map=front-left,front-right remix=no\" flags = [ \"nofail\" ] }}\n\
]\n"
    );
    fs::write(&path, content)
    .with_context(|| format!("cannot write PipeWire config {}", path.display()))
}

fn remove_pipewire_conf() {
    if let Some(path) = pipewire_conf_path() {
        let _ = fs::remove_file(path);
    }
}

fn read_saved_mic_name() -> Option<String> {
    let path = pipewire_conf_path()?;
    let text = fs::read_to_string(path).ok()?;
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix(NAME_MARKER_PREFIX) {
            let name = rest.trim();
            if !name.is_empty() {
                return Some(name.to_string());
            }
        }
    }
    None
}

/// Check if both `PhoneMicSink` and `PhoneVirtualMic` are currently loaded in `pipewire-pulse`.
pub fn is_mic_currently_loaded() -> bool {
    let Ok(list) = pactl(&["list", "short", "modules"]) else {
        return false;
    };
    let has_sink = list.lines().any(|l| {
        l.contains("module-null-sink") && l.contains(&format!("sink_name={SINK_NAME}"))
    });
    let has_source = list.lines().any(|l| {
        l.contains("module-remap-source") && l.contains(&format!("source_name={SOURCE_NAME}"))
    });
    has_sink && has_source
}

fn sink_exists() -> bool {
    let Ok(list) = pactl(&["list", "short", "sinks"]) else {
        return false;
    };
    list.lines().any(|line| {
        line.split('\t')
        .nth(1)
        .map(|name| name.trim() == SINK_NAME)
        .unwrap_or(false)
    })
}

/// Unload all `PhoneMicSink` and `PhoneVirtualMic` modules currently loaded in the sound server.
fn unload_mic_modules() {
    let Ok(list) = pactl(&["list", "short", "modules"]) else {
        return;
    };
    let mut sources = Vec::new();
    let mut sinks = Vec::new();
    for line in list.lines() {
        let mut cols = line.split('\t');
        let (Some(id), Some(name)) = (cols.next(), cols.next()) else {
            continue;
        };
        let Ok(id) = id.trim().parse::<u32>() else {
            continue;
        };
        if name == "module-remap-source" && line.contains(&format!("source_name={SOURCE_NAME}")) {
            sources.push(id);
        } else if name == "module-null-sink" && line.contains(&format!("sink_name={SINK_NAME}")) {
            sinks.push(id);
        }
    }
    // Unload sources first because they depend on the sink's monitor.
    for id in sources.into_iter().chain(sinks) {
        unload_module(id);
    }
}

fn load_mic_modules(desc: &str) -> Result<()> {
    unload_mic_modules();

    let sink_id = load_module(&[
        "module-null-sink",
        &format!("sink_name={SINK_NAME}"),
                              &format!("sink_properties=device.description={SINK_DESC}"),
                              &format!("rate={SAMPLE_RATE}"),
                              "channels=2",
                              "channel_map=front-left,front-right",
    ])
    .context("creating null sink")?;

    // Try loading with quoted description first (allows spaces in the custom name);
    // fall back to underscore-escaped description if `pactl` rejects quotes.
    let quoted_prop = format!("source_properties=\"device.description='{desc}'\"");
    let source_res = load_module(&[
        "module-remap-source",
        &format!("master={SINK_NAME}.monitor"),
                                 &format!("source_name={SOURCE_NAME}"),
                                 &quoted_prop,
                                 &format!("rate={SAMPLE_RATE}"),
                                 "channels=2",
                                 "master_channel_map=front-left,front-right",
                                 "channel_map=front-left,front-right",
                                 "remix=no",
    ])
    .or_else(|_| {
        let fallback_desc = desc.replace(' ', "_");
        load_module(&[
            "module-remap-source",
            &format!("master={SINK_NAME}.monitor"),
                    &format!("source_name={SOURCE_NAME}"),
                    &format!("source_properties=device.description={fallback_desc}"),
                    &format!("rate={SAMPLE_RATE}"),
                    "channels=2",
                    "master_channel_map=front-left,front-right",
                    "channel_map=front-left,front-right",
                    "remix=no",
        ])
    });

    if let Err(e) = source_res {
        unload_module(sink_id);
        return Err(e.context("creating virtual microphone source"));
    }

    // Ensure neither the sink nor the virtual mic source is muted or at 0% volume in Plasma.
    let _ = pactl(&["set-sink-mute", SINK_NAME, "0"]);
    let _ = pactl(&["set-sink-volume", SINK_NAME, "100%"]);
    let _ = pactl(&["set-source-mute", SOURCE_NAME, "0"]);
    let _ = pactl(&["set-source-volume", SOURCE_NAME, "100%"]);

    Ok(())
}

