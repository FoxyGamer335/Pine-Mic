/// Called at startup: checks if the permanent virtual microphone is already active
/// or configured in `~/.config/pipewire/pipewire-pulse.conf.d/99-phone-mic.conf`.
pub fn sync_existing_mic(state: &Arc<SharedState>) {
    let saved_name = read_saved_mic_name();
    if let Some(ref name) = saved_name {
        state.set_mic_name(name.clone());
    }

    if is_mic_currently_loaded() {
        let _ = pactl(&["set-sink-mute", SINK_NAME, "0"]);
        let _ = pactl(&["set-source-mute", SOURCE_NAME, "0"]);
        let active_name = state.mic_name();
        state.set_mic_active(true);
        state.set_mic_status(Some(format!("Mic active: \"{active_name}\"")));
        state.bump_mic_generation();
    } else if let Some(name) = saved_name {
        // Config exists on disk, but modules are not loaded yet in this session: load them.
        match load_mic_modules(&name) {
            Ok(()) => {
                state.set_mic_active(true);
                state.set_mic_status(Some(format!("Mic active: \"{name}\"")));
                state.bump_mic_generation();
            }
            Err(e) => {
                state.set_mic_active(false);
                state.set_mic_status(Some(format!("Failed to load saved mic: {e}")));
            }
        }
    } else {
        state.set_mic_active(false);
        state.set_mic_status(Some("Virtual microphone is not created.".into()));
    }
}

/// Permanently creates (or recreates) the virtual microphone with a custom name.
pub fn create_permanent_mic(state: &Arc<SharedState>, custom_name: &str) -> Result<()> {
    let desc = sanitize_description(custom_name);
    state.set_mic_name(desc.clone());

    if let Err(e) = load_mic_modules(&desc) {
        state.set_mic_active(false);
        state.set_mic_status(Some(format!("Error: {e}")));
        return Err(e);
    }

    if let Err(e) = write_pipewire_conf(&desc) {
        eprintln!("warning: could not save PipeWire permanent config: {e:#}");
    }

    state.set_mic_active(true);
    state.set_mic_status(Some(format!("Mic active (permanent): \"{desc}\"")));
    state.bump_mic_generation();
    Ok(())
}

/// Permanently removes the virtual microphone from the running session and disk config.
pub fn remove_permanent_mic(state: &Arc<SharedState>) -> Result<()> {
    state.set_mic_active(false);
    state.bump_mic_generation();
    unload_mic_modules();
    remove_pipewire_conf();
    state.set_mic_status(Some("Virtual microphone removed.".into()));
    Ok(())
}

